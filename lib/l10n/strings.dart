/// Texto localizado. Uso: `t('login_add_admin')` o con argumentos
/// `t('home_tasks_pending_many', {'n': '$n'})` donde el texto tiene `{n}`.
///
/// El español es el de México (el que ya usa la app) y se conserva
/// intacto; el inglés es de Estados Unidos.
String t(String key, [Map<String, String> args = const {}]) {
  final map = LangService.isEnglish ? _en : _es;
  var s = map[key] ?? _es[key] ?? key;
  args.forEach((k, v) {
    s = s.replaceAll('{$k}', v);
  });
  return s;
}

/// Nombre en vivo de un servicio semilla del catálogo: los guardados
/// quedaron en el idioma de la instalación. Null si no es semilla.
String? seedServiceName(String serviceId) {
  if (!serviceId.startsWith('seed-')) return null;
  final key = 'seed_service_${serviceId.substring(5)}';
  if (!_es.containsKey(key)) return null;
  return t(key);
}

/// Nombre de línea de servicio para mostrar: lo guardado en otro idioma
/// (semillas del catálogo, servicio rápido) se traduce en vivo.
String displayServiceLineName(String serviceId, String stored) {
  final seed = seedServiceName(serviceId);
  if (seed != null) return seed;
  if (serviceId == quickServiceId) {
    // El nombre guardado es "{Servicio rápido}: {descripción}" en el
    // idioma de cuando se creó; se traduce el prefijo y se conserva
    // la descripción tal cual la escribió el mecánico.
    final idx = stored.indexOf(': ');
    if (idx == -1) return t('my_tasks_quick_service');
    final note = stored.substring(idx + 2).trim();
    if (note.isEmpty) return t('my_tasks_quick_service');
    return '${t('my_tasks_quick_service')}: $note';
  }
  return stored;
}

/// Etiqueta visible de un puesto guardado. Los puestos se guardan como
/// texto libre (compatibilidad con instalaciones existentes en español);
/// este mapa traduce en ambas direcciones para mostrar.
String positionLabel(String stored) {
  const map = <String, String>{
    'Mecánico': 'Mechanic',
    'Técnico': 'Technician',
    'Ayudante': 'Helper',
    'Eléctrico': 'Electrician',
    'Jefe de taller': 'Shop manager',
    'Otro': 'Other',
  };
  if (!LangService.isEnglish) {
    // Si está guardado en inglés, mostrarlo en español.
    final rev = map.map((k, v) => MapEntry(v, k));
    return rev[stored] ?? stored;
  }
  return map[stored] ?? stored;
}

/// Etiquetas de los puestos de un mecánico, unidas para mostrar
/// (p. ej. "Mecánico · Eléctrico").
String positionsLabel(List<String> stored) =>
    stored.map(positionLabel).join(' · ');

